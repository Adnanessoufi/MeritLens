import { test, expect } from '@playwright/test'

test('minimal laptop entry and task navigation', async ({page}) => {
  await page.setViewportSize({width:1366,height:768})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const remoteFonts=[];page.on('request',r=>{if(/fonts\.(?:googleapis|gstatic)\.com/.test(r.url()))remoteFonts.push(r.url())})
  await page.goto('/#/')
  await expect(page.getByRole('heading',{name:'Choose your workspace'})).toBeVisible()
  await expect(page.locator('.entry-card')).toHaveCount(2)
  expect(await page.locator('.entry-card img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0))).toBe(true)
  await expect(page.locator('.mode-label,.footer,.welcome-how')).toHaveCount(0)
  expect(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight)).toBe(true)
  await page.screenshot({path:'.test-artifacts/screenshots/minimal-home.png'})
  await page.getByRole('link',{name:'Student workspace',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Upload your work',exact:true})).toBeVisible()
  await expect(page.locator('.student-guide')).toHaveCount(0)
  await page.getByRole('button',{name:'Use a sample assignment'}).click()
  await expect(page.getByRole('textbox',{name:'Assignment text'})).not.toHaveValue('')
  await expect(page.getByRole('button',{name:'Continue',exact:true})).toBeInViewport()
  await page.screenshot({path:'.test-artifacts/screenshots/minimal-upload.png'})
  for(let i=0;i<4;i++) await page.request.post('/api/assignments',{data:{title:'Compact list QA '+i,brief:'Explain dictionaries, complexity and tests in a reading-list application.',concepts:['Dictionaries']}})
  const assignmentTotal=(await(await page.request.get('/api/assignments')).json()).length
  await page.goto('/#/teacher')
  await expect(page.getByRole('heading',{name:'Your assignments'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Learning insights',exact:true})).toHaveCount(0)
  await expect(page.getByText('Concept insights',{exact:true})).toBeVisible()
  await expect(page.getByRole('link',{name:'Student experience'})).toHaveCount(0)
  await expect(page.locator('.assignment-card')).toHaveCount(3)
  await page.getByRole('button',{name:'Show more assignments',exact:true}).click()
  await expect(page.locator('.assignment-card')).toHaveCount(Math.min(6,assignmentTotal))
  while(await page.locator('.assignment-card').count()<assignmentTotal)await page.getByRole('button',{name:'Show more assignments',exact:true}).click()
  await page.getByRole('button',{name:'Show fewer',exact:true}).click()
  await expect(page.locator('.assignment-card')).toHaveCount(3)
  await expect(page.locator('.sidebar-note,.teacher-principle,.stats-grid,.teacher-workflow')).toHaveCount(0)
  const dimensions=await page.evaluate(()=>({header:document.querySelector('.header').getBoundingClientRect().height,sidebar:document.querySelector('.sidebar').getBoundingClientRect().width,row:document.querySelector('.assignment-card').getBoundingClientRect().height,gutter:document.querySelector('.page').getBoundingClientRect().left-document.querySelector('.sidebar').getBoundingClientRect().right,overflow:document.documentElement.scrollWidth>innerWidth}))
  expect(dimensions.header).toBeLessThanOrEqual(48)
  expect(dimensions.sidebar).toBeLessThanOrEqual(180)
  expect(dimensions.row).toBeLessThanOrEqual(240)
  const cards=await page.locator('.assignment-card').evaluateAll(nodes=>nodes.map(n=>n.getBoundingClientRect().width));expect(cards.every(w=>w<500)).toBe(true)
  expect(dimensions.overflow).toBe(false)
  expect(dimensions.gutter).toBeLessThanOrEqual(30)
  await page.screenshot({path:'.test-artifacts/screenshots/minimal-teacher.png'})
  await page.setViewportSize({width:1920,height:1080})
  await page.screenshot({path:'.test-artifacts/screenshots/dense-teacher-wide.png'})
  await page.setViewportSize({width:1366,height:768})
  await page.getByRole('button',{name:'Create assignment',exact:true}).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.screenshot({path:'.test-artifacts/screenshots/dense-create-assignment.png'})
  await page.getByRole('button',{name:'Cancel',exact:true}).click()
  await page.locator('.assignment-card').first().click()
  await expect(page.locator('.assignment-rubric')).toBeVisible()
  await expect(page.locator('.automatic-interview')).toHaveCount(0)
  await page.screenshot({path:'.test-artifacts/screenshots/dense-assignment-editor.png'})
  await page.goto('/#/transfer/examples')
  await expect(page.getByRole('heading',{name:'Saved example results',exact:true})).toBeVisible()
  await expect(page.locator('.transfer-example')).toHaveCount(3)
  await page.goto('/#/showcase')
  await expect(page.getByRole('heading',{name:'Examples',exact:true})).toBeVisible()
  await page.goto('/#/')
  await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('fr')
  await expect(page.getByRole('heading',{name:'Choisissez votre espace'})).toBeVisible()
  expect(errors).toEqual([])
  await page.evaluate(()=>document.fonts.ready)
  expect(await page.evaluate(()=>document.fonts.check('650 16px \"DM Sans\"','árvíztűrő tükörfúrógép'))).toBe(true)
  expect(remoteFonts).toEqual([])
})
