import {test,expect} from '@playwright/test'
test('Hungarian covers student/teacher forms, persists, and leaves source text intact',async({page})=>{
 await page.setViewportSize({width:1366,height:768})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/#/')
 await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('hu')
 await expect(page.getByRole('heading',{name:'Válassz munkaterületet',exact:true})).toBeVisible()
 await page.getByRole('link',{name:'Diákok felülete',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Töltsd fel a munkádat',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Mintafeladat használata',exact:true}).click()
 const source=await page.getByRole('textbox',{name:'Beadott munka szövege',exact:true}).inputValue()
 expect(source).toContain('Merit Lens — project demo description')
 await expect(page.getByRole('button',{name:'Tovább',exact:true})).toBeInViewport()
 await page.screenshot({path:'.test-artifacts/screenshots/hungarian-upload.png'})
 await page.goto('/#/teacher')
 await expect(page.getByRole('heading',{name:'Feladataid',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Feladat létrehozása',exact:true}).first().click()
 await expect(page.getByRole('textbox',{name:'Feladat címe',exact:true})).toBeVisible()
 await expect(page.getByLabel('Értékelési szempontok feltöltése',{exact:true})).toBeVisible()
 await page.screenshot({path:'.test-artifacts/screenshots/hungarian-create.png'})
 await page.getByRole('button',{name:'Mégse',exact:true}).click()
 await page.reload()
 await expect(page.getByRole('heading',{name:'Feladataid',exact:true})).toBeVisible()
 await page.getByRole('combobox',{name:'Nyelv',exact:true}).selectOption('en')
 await expect(page.getByRole('heading',{name:'Your assignments',exact:true})).toBeVisible()
 expect(errors).toEqual([])
})
