import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'
import {sample} from '../helpers.js'

test('Hungarian interview, saved answer, completion and teacher transcript work end to end',async({page})=>{
 await page.setViewportSize({width:1366,height:768})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/#/');await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('hu')
 await expect(page.getByRole('heading',{name:'Válassz munkaterületet',exact:true})).toBeVisible()
 await page.route('**/api/config',async r=>{const response=await r.fetch();await r.fulfill({json:{...await response.json(),voice:'openai'}})})
 // Real provider-generated Hungarian fixture, recorded earlier from fictional words.
 const audio=readFileSync('tests/fixtures/hungarian-interviewer-qa.mp3')
 await page.route('**/api/sessions/*/speech',r=>r.fulfill({contentType:'audio/mpeg',body:audio}))
 const s=await(await page.request.post('/api/submissions',{data:{requestId:crypto.randomUUID(),assignmentId:'sample-python',student:'HU interview · fictional',text:sample,language:'hu'}})).json()
 expect(s.language).toBe('hu');expect(s.question.text).toContain('Elmagyaráznád')
 const fixture=JSON.parse(readFileSync('tests/fixtures/hungarian-interviewer-qa.json','utf8'));expect(s.spokenQuestionText).toBe(fixture.text)
 await page.goto('/#/session/'+s.id)
 await expect(page.getByRole('heading',{name:'Csatlakozz a beszélgetéshez',exact:true})).toBeVisible()
 await page.getByText('Nincs elérhető kamera?',{exact:true}).click();await page.getByRole('button',{name:'Folytatás kamera nélkül',exact:true}).click()
 await page.getByText('Nincs elérhető mikrofon?',{exact:true}).click();await page.getByRole('button',{name:'Szöveges válaszok használata',exact:true}).click()
 await page.getByRole('button',{name:'Csatlakozás',exact:true}).click()
 await expect(page.getByRole('button',{name:'Kérdés elolvasása',exact:true})).toBeVisible()
 const canvas=page.getByLabel('Adnane fotója helyi szájanimációval',{exact:true})
 await expect(canvas).toBeVisible()
 await expect.poll(async()=>Number(await canvas.getAttribute('data-mouth-level'))).toBeGreaterThan(.3)
 await page.screenshot({path:'.test-artifacts/screenshots/hungarian-meeting.png'})
 await page.getByRole('button',{name:'Szöveges válasz',exact:true}).click()
 const reply='Az ISBN azonosító a kulcs, ezért nem kell végigkeresnem a teljes listát.'
 await page.getByRole('textbox',{name:'Válaszod',exact:true}).fill(reply)
 await page.getByRole('button',{name:'Válasz elküldése',exact:true}).click()
 await expect.poll(async()=>(await(await page.request.get('/api/sessions/'+s.id)).json()).answered).toBe(1)
 await page.getByRole('button',{name:'Kilépés',exact:true}).click()
 await expect(page.getByRole('heading',{name:'A beszélgetés véget ért',exact:true})).toBeVisible()
 const ended=await(await page.request.get('/api/sessions/'+s.id)).json()
 const report=await(await page.request.get('/api/reports/'+ended.reportId)).json()
 expect(report.answers[0].transcript).toBe(reply);expect(report.answers[0].question).toBe(s.question.text)
 await page.goto('/#/teacher/report/'+ended.reportId)
 await expect(page.getByRole('button',{name:'Tanári áttekintés',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Leirat és időzítés',exact:true}).click()
 await page.locator('.transcript > summary').first().click()
 await expect(page.locator('.transcript-body > blockquote').first()).toHaveText(reply)
 await page.screenshot({path:'.test-artifacts/screenshots/hungarian-transcript.png'})
 expect(errors).toEqual([])
})
