import {test,expect} from '@playwright/test'
test('small challenge focus input is optional, saved from creation and editable in settings',async({page})=>{
 await page.goto('/#/teacher')
 await page.getByRole('button',{name:'Create assignment',exact:true}).first().click()
 const dialog=page.getByRole('dialog')
 await dialog.getByLabel('Assignment title',{exact:true}).fill('Matlab focus UI')
 await dialog.getByLabel('Instructions',{exact:true}).fill('Calculate the slope and draw the tangent for the uploaded function.')
 await expect(dialog.getByLabel('Concepts to evaluate',{exact:true})).toHaveCount(0)
 await dialog.getByRole('combobox',{name:'Interview mode',exact:true}).selectOption('transfer')
 await dialog.getByLabel('Concepts to evaluate',{exact:true}).fill('Slope, Tangent')
 await dialog.getByRole('button',{name:'Create assignment',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Matlab focus UI',exact:true})).toBeVisible()
 const assignmentId=page.url().split('/').pop()
 let saved=await(await page.request.get('/api/teacher/assignments/'+assignmentId)).json()
 expect(saved.challenge_concepts).toEqual(['Slope','Tangent'])
 await page.locator('.assignment-settings > summary').click()
 await expect(page.getByLabel('Concepts to evaluate',{exact:true})).toHaveValue('Slope, Tangent')
 await page.getByLabel('Concepts to evaluate',{exact:true}).fill('Slope, Roots')
 await page.getByRole('button',{name:'Save assignment settings',exact:true}).click()
 await expect(page.getByText('Settings saved. Existing interviews keep their original mode and timing.',{exact:true})).toBeVisible()
 saved=await(await page.request.get('/api/teacher/assignments/'+assignmentId)).json()
 expect(saved.challenge_concepts).toEqual(['Slope','Roots'])
 await page.setViewportSize({width:390,height:844})
 await page.getByLabel('Concepts to evaluate',{exact:true}).scrollIntoViewIfNeeded()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:'.test-artifacts/screenshots/challenge-concepts-mobile.png'})
 await page.getByRole('combobox',{name:'Interview mode',exact:true}).selectOption('standard')
 await expect(page.getByLabel('Concepts to evaluate',{exact:true})).toHaveCount(0)
})
