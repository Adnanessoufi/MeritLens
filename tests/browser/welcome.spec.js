import { test, expect } from '@playwright/test'

test('first visit gives two clear roles and guides each next step', async ({ page }) => {
  await page.setViewportSize({ width: 1366, height: 768 })
  await page.goto('/#/')
  await expect(page.locator('.welcome-role')).toHaveCount(2)
  await expect(page.locator('.welcome-how li')).toHaveCount(3)
  await expect(page.getByText('Gap flagged', { exact: true })).toHaveCount(0)
  const student = page.getByRole('link', { name: 'I’m a student', exact: true })
  const teacher = page.getByRole('link', { name: 'I’m a teacher', exact: true })
  for (const action of [student, teacher, page.locator('.welcome-examples a')]) {
    const bounds = await action.boundingBox()
    expect(bounds.y + bounds.height).toBeLessThanOrEqual(768)
  }
  await student.click()
  await expect(page.getByRole('heading', { name: 'Upload your work.', exact: true })).toBeVisible()
  await expect(page.locator('.upload-steps li')).toHaveCount(3)
  await expect(page.getByLabel('Your name', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Interview mode')).not.toBeVisible()
  await page.locator('.upload-options summary').click()
  await page.getByLabel('Interview mode').selectOption('transfer')
  await expect(page.getByLabel('Concept pairs')).toBeVisible()
  await page.locator('.upload-options summary').click()
  await page.getByRole('button', { name: /Use a sample assignment/ }).click()
  await expect(page.getByLabel('Assignment text')).not.toBeEmpty()
  const prepareBounds = await page.getByRole('button', { name: 'Upload & prepare my defence', exact: true }).boundingBox()
  expect(prepareBounds.y + prepareBounds.height).toBeLessThanOrEqual(768)
  await page.screenshot({ path: '.test-artifacts/screenshots/laptop-first-upload.png', fullPage: false })
  await page.getByRole('link', { name: 'Back to home', exact: true }).click()
  await page.getByRole('link', { name: 'I’m a teacher', exact: true }).click()
  await expect(page.locator('.teacher-workflow li')).toHaveCount(3)
  await page.getByRole('button', { name: 'Create assignment', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByLabel('Assignment title', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.goto('/#/student/transfer-python/transfer')
  await expect(page.getByLabel('Concept pairs')).toBeVisible()
  await page.goto('/#/')
  await page.getByLabel('Language', { exact: true }).selectOption('fr')
  await expect(page.getByRole('heading', { name: 'Montrez le raisonnement derrière le travail.' })).toBeVisible()
  await page.getByRole('link', { name: 'Je suis élève', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Envoyez votre travail.', exact: true })).toBeVisible()
  await page.getByLabel('Language', { exact: true }).selectOption('ar')
  await expect(page.getByRole('heading', { name: 'ارفع عملك.', exact: true })).toBeVisible()
  await page.getByLabel('Language', { exact: true }).selectOption('en')
})
